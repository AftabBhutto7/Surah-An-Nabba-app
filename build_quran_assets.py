#!/usr/bin/env python3
import urllib.request
import json
import re

print("Fetching all 83 verses of Surah Yaseen from Quran.com API...")

# Translation IDs on Quran.com:
# 20: Saheeh International (English)
# 97: Fateh Muhammad Jalandhri (Urdu)
url = "https://api.quran.com/api/v4/verses/by_chapter/36?language=en&words=true&translations=20,97&fields=text_uthmani&per_page=83"
req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (SurahYaseenApp/1.0)"})

with urllib.request.urlopen(req, timeout=20) as resp:
    data = json.loads(resp.read().decode("utf-8"))

verses_raw = data.get("verses", [])
print(f"Retrieved {len(verses_raw)} raw verses.")

def clean_html(raw_html):
    if not raw_html:
        return ""
    clean = re.sub(r"<[^>]+>", "", raw_html)
    return clean.strip()

