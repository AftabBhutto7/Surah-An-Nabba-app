def identify_tajweed(arabic_text):
    tokens = []
    # Ghunnah: نّ or مّ
    if "نّ" in arabic_text or "مّ" in arabic_text:
        match = re.search(r"[نم]ّ", arabic_text)
        if match:
            tokens.append({
                "rule": "Ghunnah",
                "arabic": match.group(0),
                "explanation": "Nunnation/Mimmation with nasal prolongation for 2 counts (Ghunnah)."
            })
    # Qalqalah: ق ط ب ج د with sukoon
    qalqalah_match = re.search(r"[قطبجد]ْ|[قطبجد]$", arabic_text)
    if qalqalah_match:
        tokens.append({
            "rule": "Qalqalah",
            "arabic": qalqalah_match.group(0),
            "explanation": "Echoing/bouncing sound on Qaf, Taa, Baa, Jeem, or Daal when sakin."
        })
    # Madd: ٓ (maddah mark)
    if "ٓ" in arabic_text or "ٰ" in arabic_text:
        tokens.append({
            "rule": "Madd",
            "arabic": "ـٓـ",
            "explanation": "Prolongation of the vowel sound for 4 to 6 vowel counts."
        })
    # Ikhfa: noon sakin or tanween followed by ikhfa letters (ت ث ج د ذ ز س ش ص ض ط ظ ف ق ك)
    if re.search(r"ن[تثجدذزسشصضطظفقك]", arabic_text):
        tokens.append({
            "rule": "Ikhfa",
            "arabic": "إخفاء",
            "explanation": "Hiding the sound of Noon Sakinah between Izhar and Idgham with nasalization."
        })
    # Idgham: noon sakin or tanween followed by يرملون
    if re.search(r"ن[يرملون]", arabic_text):
        tokens.append({
            "rule": "Idgham",
            "arabic": "إدغام",
            "explanation": "Merging the Noon Sakinah into the following letter."
        })
    # Default fallback rule if none matched
    if not tokens:
        tokens.append({
            "rule": "Tarqeeq / Tafkheem",
            "arabic": "ترقيق وتفخيم",
            "explanation": "Proper lightness or heaviness of Arabic letters according to vowel position."
        })
    return tokens

enriched_ayahs = []

for v in verses_raw:
    v_num = v["verse_number"]
    text_uthmani = v.get("text_uthmani", "").strip()
    translations = v.get("translations", [])

    trans_en = ""
    trans_ur = ""
    for t in translations:
        res_id = t.get("resource_id")
        t_text = clean_html(t.get("text", ""))
        if res_id == 20: # Sahih International
            trans_en = t_text
        elif res_id == 97: # Jalandhri Urdu
            trans_ur = t_text

    raw_words = v.get("words", [])
    words_list = []
    transliteration_parts = []

    for w in raw_words:
        if w.get("char_type_name") != "word":
            continue
        pos = w.get("position", 1)
        w_ar = w.get("text_uthmani") or w.get("text", "")
        w_en = clean_html(w.get("translation", {}).get("text", ""))
        w_tr = clean_html(w.get("transliteration", {}).get("text", ""))
        if w_tr:
            transliteration_parts.append(w_tr)

        # Look up root and grammar analysis
        # Strip diacritics for dictionary lookup
        clean_w = re.sub(r"[\u064B-\u065F\u0670\u06D6-\u06ED]", "", w_ar)
        dict_match = ROOT_DICT.get(w_ar) or ROOT_DICT.get(clean_w) or {}

        words_list.append({
            "position": pos,
            "arabic": w_ar,
            "translationEn": w_en,
            "translationUr": "", # populated or inferred
            "transliteration": w_tr,
            "root": dict_match.get("root", "—"),
            "partOfSpeech": dict_match.get("pos", "كلمة قرآنية"),
            "grammarRole": dict_match.get("role", "معربة بحسب السياق"),
            "caseState": dict_match.get("case", "مبني / معرب"),
            "explanation": f"Ayah {v_num}, Word {pos}"
        })

    # High-quality audio URLs for Mishary Alafasy and Abdul Basit
    # 3-digit surah 036, 3-digit ayah e.g. 036001.mp3
    padded_surah = "036"
    padded_ayah = str(v_num).zfill(3)
    audio_code = f"{padded_surah}{padded_ayah}"

    ayah_entry = {
        "number": v_num,
        "surahNumber": 36,
        "arabicUthmani": text_uthmani,
        "translationEn": trans_en,
        "translationUr": trans_ur,
        "transliteration": " ".join(transliteration_parts),
        "theme": get_theme(v_num),
        "audioUrlAlafasy": f"https://everyayah.com/data/Alafasy_128kbps/{audio_code}.mp3",
        "audioUrlAbdulBasit": f"https://everyayah.com/data/Abdul_Basit_Murattal_192kbps/{audio_code}.mp3",
        "audioUrlGhamadi": f"https://everyayah.com/data/Ghamadi_40kbps/{audio_code}.mp3",
        "words": words_list,
        "tajweedTokens": identify_tajweed(text_uthmani)
    }
    enriched_ayahs.append(ayah_entry)

